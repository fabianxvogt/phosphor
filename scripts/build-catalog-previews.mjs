// Bake every authored catalogue look once; own looks/variations remain local.
// Re-run after changing a renderer or its authored presets. No UI interaction.
import { writeFile } from "node:fs/promises";
import { serve, launch, openLab } from "./browser-runtime.mjs";
import { lookId } from "../catalog.mjs";
import { renderLook } from "../tests/browser/client.mjs";
import { THUMBNAIL_PALETTE, thumbnailKey } from "../thumbnail-palette.mjs";
const server = await serve(".", 48219);
const runtime = await launch({ rig: true, headless: true });
try {
  const lab = await openLab(runtime.browser, server.url);
  const looks = await lab.page.evaluate(() => {
    const { scenes, presetSnapshot } = window.__phosphorLab;
    return scenes.flatMap((scene) =>
      scene.presets.map((preset, index) => ({
        sceneId: scene.id,
        index,
        snapshot: presetSnapshot(scene, index),
      })),
    );
  });
  const previews = {};
  for (const look of looks) {
    const result = await lab.page.evaluate(renderLook, {
      ...look,
      snapshot: { ...look.snapshot, palette: THUMBNAIL_PALETTE },
      width: 512,
      height: 288,
      frames: 60,
      capture: false,
      level: 0.5,
      base: 0.5,
    });
    if (result.glError || result.nonFinite)
      throw new Error(`Invalid render: ${look.sceneId}:${look.index}`);
    const url = await lab.page.evaluate(() => {
      const { engine } = window.__phosphorLab;
      engine.present();
      const canvas = document.createElement("canvas");
      canvas.width = 512;
      canvas.height = 288;
      canvas.getContext("2d").drawImage(engine.canvas, 0, 0);
      return canvas.toDataURL("image/webp", 0.85);
    });
    previews[lookId(look.snapshot)] = {
      key: thumbnailKey(look.snapshot),
      url,
    };
    if (Object.keys(previews).length % 32 === 0)
      console.log(`${Object.keys(previews).length}/${looks.length} previews`);
  }
  if (lab.errors.length) throw new Error(lab.errors.join("\n"));
  const body =
    "// Generated by scripts/build-catalog-previews.mjs. Palette-independent 512×288 WebP images.\nexport const PREVIEWS = " +
    JSON.stringify(previews, null, 2) +
    ";\n";
  await writeFile(new URL("../catalog-previews.mjs", import.meta.url), body);
  console.log(
    `Saved ${looks.length} previews; ${Math.round(Buffer.byteLength(body) / 1024)} KiB`,
  );
} finally {
  await runtime.stop();
  await server.close();
}
